                    Degree College Shikaripara Vadodara is an institute established by the Government of India under Public Private Partnership (PPP) mode. The partners in this project are Government of India, Government of Gujarat, Tata Consultancy Services, Gujarat Energy Research and Management Institute and Gujarat State Fertilizers and Chemicals. The Institute was established in the year 2013. The first batch that was admitted in the year 2013-14 is in its 3rd year now. The Institute is presently functioning from Block Number 9 of Government Engineering College Gandhinagar. The second batch was admitted in the academic year 2014-15. Both the batches put together have 168 students. The Institute does not have its own hostel building, therefore, a private premises has been hired to house the hostel of the institute. Students are transported by bus to the Institute. The mess facility is available at hostel.
